import csv,datetime as dt,hashlib,io,json,re,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from tools.common import node_registry
from tools.runtime import GuardError,file_lock,atomic_replace
COLUMNS=['signal_id','observed_at','captured_at','type','summary','context','interpretation','source','source_ref','related_ids','status','action_ref']
TYPES={'request','complaint','error','observation','suggestion'}
STATUSES={'new','reviewed','actioned','dismissed'}
TRANSITIONS={'new':{'new','reviewed','actioned','dismissed'},'reviewed':{'reviewed','actioned','dismissed'},'actioned':{'actioned','reviewed'},'dismissed':{'dismissed','reviewed'}}
def parts(s):return [x.strip() for x in s.split(';') if x.strip()]
def _date(value,required=False,aware=False):
    if not value:
        if required:raise GuardError('timestamp required')
        return
    try:
        if not aware and re.fullmatch(r'\d{4}-\d{2}-\d{2}',value):dt.date.fromisoformat(value);return
        parsed=dt.datetime.fromisoformat(value.replace('Z','+00:00'))
        if parsed.tzinfo is None:raise ValueError('timezone required')
    except (ValueError,TypeError):raise GuardError('invalid date/timezone')

def validate(rows,registry):
    seen=set()
    for r in rows:
        if set(r)!=set(COLUMNS) or not all(isinstance(v,str) for v in r.values()):raise GuardError('invalid signal columns/types')
        if not re.fullmatch(r'SIG-[0-9]{6}',r['signal_id']) or r['signal_id']=='SIG-000000' or r['signal_id'] in seen:raise GuardError('invalid/duplicate SIG ID')
        seen.add(r['signal_id'])
        if r['type'] not in TYPES or r['status'] not in STATUSES:raise GuardError('invalid type/status')
        if not r['summary'].strip() or not r['source'].strip():raise GuardError('summary/source required')
        _date(r['captured_at'],True,True);_date(r['observed_at'])
        if r['status']!='new' and not r['source_ref'].strip() and not re.search(r'missing_source_ref:\s*\S',r['context']):raise GuardError('source evidence or explicit missing-source reason required')
        if r['status'] in ('actioned','dismissed') and not r['action_ref'].strip():raise GuardError('action/decision reason required')
        related=parts(r['related_ids'])
        if len(set(related))!=len(related):raise GuardError('duplicate related ID')
        for id in related:
            if id not in registry or registry[id]['entity_type'] not in ('domain','feature','idea'):raise GuardError('unknown/wrong related ID')
        for ref in parts(r['action_ref']):
            if re.match(r'^(?:I|T|BL|DEC|F|D|SIG)-',ref) and ref not in registry:raise GuardError('unknown action ID')
    return True

def load(root):
    root=Path(root).resolve();p=root/'signals/signals.csv'
    if p.resolve()!=p or p.is_symlink():raise GuardError('signal path must not be symlink')
    data=p.read_bytes()
    with io.StringIO(data.decode('utf-8'),newline='') as f:
        reader=csv.DictReader(f)
        if reader.fieldnames!=COLUMNS:raise GuardError('signal header/order mismatch')
        rows=list(reader)
    validate(rows,node_registry(root))
    return rows,hashlib.sha256(data).hexdigest()

def _bytes(rows):
    buf=io.StringIO(newline='');w=csv.DictWriter(buf,fieldnames=COLUMNS);w.writeheader();w.writerows(rows);return buf.getvalue().encode('utf-8')
def _key(r):
    norm=lambda s:' '.join(s.casefold().split())
    return (norm(r['source']),r['source_ref'].strip(),r['type'],norm(r['summary']),norm(r['context'])) if r['source_ref'].strip() else None

def capture(root,payload,expected_hash,actor):
    if actor!='coordinator':raise GuardError('only coordinator signal writer')
    if set(payload)-set(COLUMNS):raise GuardError('unknown capture field')
    if any(k in payload for k in ('signal_id','captured_at','status')):raise GuardError('capture ID/time/status generated by writer')
    root=Path(root).resolve()
    with file_lock(root,'signals/signals.csv'):
        rows,h=load(root)
        if h!=expected_hash:raise GuardError('signal CAS conflict')
        r={c:'' for c in COLUMNS};r.update(payload)
        number=max([int(x['signal_id'][4:]) for x in rows]+[0])+1
        if number>999999:raise GuardError('signal ID capacity exhausted')
        r.update(signal_id=f'SIG-{number:06d}',captured_at=dt.datetime.now(dt.timezone.utc).isoformat(),status='new')
        validate([*rows,r],node_registry(root))
        key=_key(r)
        if key is not None:
            old=next((x for x in rows if _key(x)==key),None)
            if old:return {'row':old,'created':False,'hash':h}
        data=_bytes([*rows,r]);atomic_replace(root/'signals/signals.csv',data)
        return {'row':r,'created':True,'hash':hashlib.sha256(data).hexdigest()}

def update(root,id,patch,expected_hash,actor):
    if actor!='coordinator':raise GuardError('only coordinator signal writer')
    if set(patch)-set(COLUMNS) or any(k in patch for k in ('signal_id','captured_at')):raise GuardError('immutable/unknown signal field')
    root=Path(root).resolve()
    with file_lock(root,'signals/signals.csv'):
        rows,h=load(root)
        if h!=expected_hash:raise GuardError('signal CAS conflict')
        ix=next((n for n,r in enumerate(rows) if r['signal_id']==id),None)
        if ix is None:raise GuardError('unknown signal ID')
        old=rows[ix];r={**old,**patch}
        if r['status'] not in TRANSITIONS[old['status']]:raise GuardError('invalid signal status transition')
        if old['status'] in ('actioned','dismissed') and r['status']=='reviewed' and not patch.get('action_ref','').strip():raise GuardError('reopen requires explicit reason in action_ref')
        rows[ix]=r;validate(rows,node_registry(root));data=_bytes(rows);atomic_replace(root/'signals/signals.csv',data)
        return {'row':r,'hash':hashlib.sha256(data).hexdigest()}

def filter_rows(root,related_id=None,status=None):
    rows,h=load(root)
    if status is not None and status not in STATUSES:raise GuardError('invalid filter status')
    return [r for r in rows if (related_id is None or related_id in parts(r['related_ids'])) and (status is None or r['status']==status)]
def get(root,id):
    rows,h=load(root)
    row=next((r for r in rows if r['signal_id']==id),None)
    if row is None:raise GuardError('unknown signal ID')
    return row

def spreadsheet_export(root,destination):
    root=Path(root).resolve();dst=(root/destination).resolve()
    if root not in dst.parents or not dst.relative_to(root).as_posix().startswith('artifacts/') or dst.exists():raise GuardError('new export path under artifacts required')
    rows,h=load(root)
    safe=lambda s: "'"+s if s.lstrip().startswith(('=','+','-','@','\t','\r')) or s.startswith(('\t','\r')) else s
    exported=[{k:safe(v) for k,v in row.items()} for row in rows]
    atomic_replace(dst,_bytes(exported));return {'source_hash':h,'rows':len(rows),'canonical_modified':False}

